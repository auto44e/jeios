"""Regenerate tests/fixtures/qemu_virt82_dtb.h — the real QEMU virt-8.2 DTB as a
C byte array (issue #52).

The fixture is QEMU-GENERATED data describing the pinned emulated board, not
imported third-party source. It is committed as a C array (not a raw .dtb) per
AGENTS.md rule 11. Only the live extent is kept (header totalsize still says the
full padded size), which also exercises the totalsize > len path.

The command line MUST match tools/smoke_arm.py's machine/memory pin, and uses
dtb-randomness=off so the blob is byte-reproducible (otherwise QEMU injects
fresh rng-seed / kaslr-seed in /chosen on every run).
"""
import hashlib
import struct
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tests" / "fixtures" / "qemu_virt82_dtb.h"
MACHINE = "virt-8.2,gic-version=2,virtualization=off,secure=off,dtb-randomness=off"
MEMORY = "256M"


def main():
    with tempfile.TemporaryDirectory() as d:
        dtb = Path(d) / "virt.dtb"
        cmd = ["qemu-system-aarch64", "-M", f"{MACHINE},dumpdtb={dtb}",
               "-cpu", "cortex-a72", "-smp", "1", "-m", MEMORY, "-nographic"]
        subprocess.run(cmd, check=True, capture_output=True)
        full = dtb.read_bytes()
        qver = subprocess.check_output(["qemu-system-aarch64", "--version"],
                                       text=True).splitlines()[0]
    magic, total, ostruct, ostr, orsv, ver, lcv, _cpu, sstr, sstruct = \
        struct.unpack(">10I", full[:40])
    if magic != 0xD00DFEED:
        sys.exit("not an FDT")
    # live extent: rsvmap terminator end, struct end, strings end
    p = orsv
    while True:
        a, s = struct.unpack(">QQ", full[p:p + 16])
        p += 16
        if a == 0 and s == 0:
            break
    used = max(p, ostruct + sstruct, ostr + sstr)
    live = full[:used]
    crc = zlib.crc32(live) & 0xFFFFFFFF
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* GENERATED by tools/gen_dtb_fixture.py — do not edit by hand.",
        f" * Source: {qver}",
        f" * Command: {' '.join(cmd[:2])} {MACHINE},dumpdtb=<tmp> {' '.join(cmd[3:])}",
        f" * Header: totalsize={total} version={ver}/{lcv} rsvmap@{orsv} "
        f"struct@{ostruct}+{sstruct} strings@{ostr}+{sstr}",
        f" * Full dump sha256={hashlib.sha256(full).hexdigest()}",
        f" * Live extent {used} bytes sha256={hashlib.sha256(live).hexdigest()}",
        " * QEMU-generated board description data, not imported source. */",
        "#ifndef JEIOS_TEST_QEMU_VIRT82_DTB_H",
        "#define JEIOS_TEST_QEMU_VIRT82_DTB_H",
        "#include <stdint.h>",
        f"#define QEMU_VIRT82_DTB_LEN {used}u",
        f"#define QEMU_VIRT82_DTB_TOTALSIZE {total}u",
        f"#define QEMU_VIRT82_DTB_CRC32 0x{crc:08x}u",
        "static const uint8_t qemu_virt82_dtb[QEMU_VIRT82_DTB_LEN] = {",
    ]
    for i in range(0, used, 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in live[i:i + 12]) + ",")
    lines += ["};", "#endif", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({used} live bytes, totalsize {total}, crc32 0x{crc:08x})")


if __name__ == "__main__":
    main()
